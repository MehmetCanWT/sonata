//! Shared English and Turkish UI localization catalog for Linux Sonata clients.
//!
//! 1. **Language Preference (`AppLanguage`)**: Serializable `en` / `tr` selector defaulting to English (`En`) for Desktop and TUI.
//! 2. **Static String Catalog (`UiStrings`)**: Zero-allocation compile-time verified translation tables (`EN`, `TR`) powering menus, settings, modals, empty states, and playback controls.

use serde::{Deserialize, Serialize};

/// Supported UI languages for Sonata Desktop and TUI (defaults to English).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
#[serde(rename_all = "lowercase")]
pub enum AppLanguage {
    #[default]
    En,
    Tr,
    Ru,
}

impl AppLanguage {
    /// Returns the native display label for this language.
    pub fn label(self) -> &'static str {
        match self {
            Self::En => "English",
            Self::Tr => "Türkçe",
            Self::Ru => "Русский",
        }
    }

    /// Returns the BCP-47 language code.
    pub fn code(self) -> &'static str {
        match self {
            Self::En => "en",
            Self::Tr => "tr",
            Self::Ru => "ru",
        }
    }

    /// Cycles forward through supported languages.
    pub fn next(self) -> Self {
        match self {
            Self::En => Self::Tr,
            Self::Tr => Self::Ru,
            Self::Ru => Self::En,
        }
    }

    /// Cycles backward through supported languages.
    pub fn prev(self) -> Self {
        match self {
            Self::En => Self::Ru,
            Self::Tr => Self::En,
            Self::Ru => Self::Tr,
        }
    }
}

/// Returns the static UI translation catalog for the requested language.
pub fn strings(lang: AppLanguage) -> &'static UiStrings {
    match lang {
        AppLanguage::En => &EN,
        AppLanguage::Tr => &TR,
        AppLanguage::Ru => &RU,
    }
}

