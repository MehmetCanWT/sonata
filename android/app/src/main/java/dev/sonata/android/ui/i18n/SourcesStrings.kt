/**
 * Resolves [SourcesStrings] for [lang], using [systemLocale] when [lang] is [AppLanguage.SYSTEM].
 */
fun sourcesStrings(
    lang: AppLanguage,
    systemLocale: Locale = Locale.getDefault(),
): SourcesStrings = when (lang) {
    AppLanguage.ENGLISH -> EnglishSourcesStrings
    AppLanguage.TURKISH -> TurkishSourcesStrings
    AppLanguage.RUSSIAN -> RussianSourcesStrings
    AppLanguage.SYSTEM -> when (systemLocale.language.lowercase(Locale.ROOT)) {
        "tr" -> TurkishSourcesStrings
        "ru" -> RussianSourcesStrings
        else -> EnglishSourcesStrings
    }
}
